    func string(in language: AppLanguage, arguments: [CVarArg] = []) -> String {
        let resolved = language.resolved()
        let template = resolved == .simplifiedChinese ? rawValue : english
        guard !arguments.isEmpty else { return template }
        return String(format: template, locale: Locale(identifier: resolved.rawValue), arguments: arguments)
    }
}

enum WallpaperError: LocalizedError {
    case missingVideo, invalidVideo, playbackFailed
    var key: TextKey {
        switch self {
        case .missingVideo: return .missingVideo
        case .invalidVideo: return .invalidVideo
        case .playbackFailed: return .playbackFailed
        }
    }
    var errorDescription: String? { key.string(in: .system) }
}
